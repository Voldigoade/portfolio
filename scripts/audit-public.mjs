import { execFileSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import sharp from 'sharp';

const git = (args) =>
  execFileSync('git', args, {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
const files = [
  ...new Set(
    git(['ls-files', '--cached', '--others', '--exclude-standard', '-z'])
      .split('\0')
      .filter(Boolean),
  ),
].filter(existsSync);
const failures = [];
const expectedEmail = '245930475+Voldigoade@users.noreply.github.com';
const username = process.env.USERNAME;
const patterns = [
  /[A-Z]:\\Users\\/i,
  /\/(?:Users|home)\//,
  /(?:gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|sk-proj-[A-Za-z0-9_-]{20,})/,
  /-----BEGIN (?:RSA |OPENSSH |EC )?PRIVATE KEY-----/,
  /(?:generated by|made with)\s+(?:AI|Codex|ChatGPT)/i,
];

for (const file of files) {
  if (
    /(?:^|\/)(?:\.env(?:\.|$)|\.vercel|\.astro|node_modules|dist|coverage|test-results)/.test(
      file,
    )
  )
    failures.push(`${file}: private or generated artifact`);
  const buffer = readFileSync(file);
  if (file.endsWith('.png')) {
    const metadata = await sharp(buffer).metadata();
    if (metadata.exif || metadata.iptc || metadata.xmp)
      failures.push(`${file}: unnecessary image metadata`);
    continue;
  }
  if (buffer.includes(0)) continue;
  const content = buffer.toString('utf8');
  if (patterns.some((pattern) => pattern.test(content)))
    failures.push(`${file}: sensitive content pattern`);
  if (
    username &&
    username.length > 3 &&
    content.toLowerCase().includes(username.toLowerCase())
  )
    failures.push(`${file}: machine identity`);
  const emails =
    content.match(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g) || [];
  const unapprovedEmails = emails.filter(
    (email) =>
      email !== expectedEmail &&
      !file.startsWith('public/licenses/') &&
      !(file.startsWith('tests/') && email.endsWith('@example.invalid')),
  );
  if (unapprovedEmails.length) failures.push(`${file}: email requires review`);
}

if (git(['config', '--local', 'user.name']) !== 'Voldigoade')
  failures.push('Repository author name is not pseudonymous');
if (git(['config', '--local', 'user.email']) !== expectedEmail)
  failures.push('Repository email is not the public noreply identity');
const remotes = git(['remote', '-v']);
if (
  remotes &&
  !/^origin\s+https:\/\/github\.com\/Voldigoade\/portfolio(?:\.git)?\s+\((?:fetch|push)\)$/m.test(
    remotes,
  )
)
  failures.push('Unexpected remote target');
const hasHead = (() => {
  try {
    git(['rev-parse', '--verify', 'HEAD']);
    return true;
  } catch {
    return false;
  }
})();
let commits = 0;
if (hasHead) {
  for (const identity of git([
    'log',
    '--all',
    '--format=%an|%ae|%cn|%ce|%ai|%ci',
  ]).split('\n')) {
    commits++;
    const [
      author,
      authorEmail,
      committer,
      committerEmail,
      authorDate,
      committerDate,
    ] = identity.split('|');
    if (
      author !== 'Voldigoade' ||
      committer !== 'Voldigoade' ||
      authorEmail !== expectedEmail ||
      committerEmail !== expectedEmail
    )
      failures.push('Commit identity mismatch');
    if (!authorDate.endsWith('+0000') || !committerDate.endsWith('+0000'))
      failures.push('Commit timestamp offset is not UTC');
  }
}
console.log(
  JSON.stringify(
    { trackedFiles: files.length, commits, safeLocalIdentity: true, failures },
    null,
    2,
  ),
);
if (failures.length) process.exitCode = 1;
